package io.github.aequicor.heartbeat.designsystem.foundation

/**
 * Two-point spacing scale in logical units. Screens use a value from this scale instead of a new
 * measurement, and renderer adapters convert the unit to their own dimension type.
 */
public object HbSpace {
    public const val None: Int = 0
    public const val Two: Int = 2
    public const val Four: Int = 4
    public const val Six: Int = 6
    public const val Eight: Int = 8
    public const val Twelve: Int = 12
    public const val Sixteen: Int = 16
    public const val Twenty: Int = 20
    public const val TwentyFour: Int = 24
    public const val ThirtyTwo: Int = 32
    public const val Forty: Int = 40
    public const val FortyEight: Int = 48
    public const val SixtyFour: Int = 64
}
