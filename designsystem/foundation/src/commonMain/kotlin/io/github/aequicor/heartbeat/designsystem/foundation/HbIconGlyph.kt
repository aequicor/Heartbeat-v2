package io.github.aequicor.heartbeat.designsystem.foundation

/**
 * Icon identifiers of the portable contract (HB-DS, icons). The vocabulary is semantic: an icon
 * names a meaning, and a renderer adapter draws the same identifier in its own style. A component
 * uses the identifier together with an accessible action name, never the glyph name.
 */
public enum class HbIconGlyph {
    ChevronDown,
    Close,
    Plus,
    Minus,
    Check,
    Search,
    Send,
    Stop,
    More,
    Eye,
    EyeOff,
}
