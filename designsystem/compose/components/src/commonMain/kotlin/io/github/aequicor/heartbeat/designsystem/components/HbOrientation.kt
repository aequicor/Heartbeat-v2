package io.github.aequicor.heartbeat.designsystem.components

/** Orientation of a separator or a splitter in the layout. */
enum class HbOrientation {
    /** A horizontal element; a splitter of this orientation separates rows and resizes vertically. */
    Horizontal,

    /** A vertical element; a splitter of this orientation separates columns and resizes horizontally. */
    Vertical,
}
