/**
 * Icon-only action (HB-DS-015). [contentDescription] is the action name, such as "Stop response",
 * not the glyph name, so assistive services announce what the control does. The effective target
 * comes from the dense geometry and the focus outline is drawn around it.
 */
@Composable
fun HbIconButton(
    contentDescription: String,
    onClick: () -> Unit,
    modifier: Modifier = Modifier,
    enabled: Boolean = true,
    content: @Composable () -> Unit,
) {
    val colors = HbThemeTokens.colors
    var focused by remember { mutableStateOf(false) }

    Box(
        modifier = modifier
            .size(HbSizes.minimumTarget)
            .clip(HbShapes.Small)
            .onFocusChanged { focused = it.isFocused }
            .hbFocusRing(focused = focused, shape = HbShapes.Small, color = colors.focus)
            .clickable(
                enabled = enabled,
                role = Role.Button,
                onClick = onClick,
            )
            .semantics { this.contentDescription = contentDescription },
        contentAlignment = Alignment.Center,
    ) {
        content()
    }
}

